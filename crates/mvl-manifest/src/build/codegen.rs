//! Render the owned manifest as a Rust `const` expression for `include!`.

use std::fmt::Write;

use super::graph::{OwnedPackage, OwnedSource};
use super::OwnedManifest;

const P: &str = "::mvl_manifest";

fn s(v: &str) -> String {
    // `str`'s Debug output is a valid Rust string literal.
    format!("{v:?}")
}

fn opt(v: &Option<String>) -> String {
    match v {
        Some(v) => format!("Some({})", s(v)),
        None => "None".to_string(),
    }
}

fn list(items: &[String]) -> String {
    let parts: Vec<String> = items.iter().map(|i| s(i)).collect();
    format!("&[{}]", parts.join(", "))
}

fn kind(k: &str) -> &'static str {
    match k {
        "build" => "Build",
        "proc-macro" => "ProcMacro",
        _ => "Runtime",
    }
}

fn source(src: &OwnedSource) -> String {
    match src {
        OwnedSource::Registry { url } => {
            format!("{P}::PackageSource::Registry {{ url: {} }}", s(url))
        }
        OwnedSource::Git { url, commit } => format!(
            "{P}::PackageSource::Git {{ url: {}, commit: {} }}",
            s(url),
            s(commit)
        ),
        OwnedSource::Path => format!("{P}::PackageSource::Path"),
        OwnedSource::Workspace => format!("{P}::PackageSource::Workspace"),
    }
}

fn packages(pkgs: &[OwnedPackage]) -> String {
    let mut out = String::from("&[\n");
    for p in pkgs {
        let _ = writeln!(
            out,
            "        {P}::PackageInfo {{ name: {}, version: {}, purl: {}, license: \"\", kind: {P}::PackageKind::{}, source: {}, checksum: {} }},",
            s(&p.name),
            s(&p.version),
            s(&p.purl),
            kind(p.kind),
            source(&p.source),
            s(&p.checksum)
        );
    }
    out.push_str("    ]");
    out
}

pub fn render(m: &OwnedManifest) -> String {
    let b = &m.build;
    let mut o = String::new();
    o.push_str("// @generated by mvl_manifest::build::generate(). Do not edit.\n");
    let _ = writeln!(o, "{P}::Manifest {{");
    let _ = writeln!(o, "    app_name: {},", s(&m.app_name));
    let _ = writeln!(o, "    app_version: {},", s(&m.app_version));
    let _ = writeln!(o, "    mvl_version: {},", s(&m.mvl_version));
    let _ = writeln!(o, "    runtime_version: {},", s(&m.runtime_version));
    let _ = writeln!(o, "    packages: {},", packages(&m.packages));
    let _ = writeln!(o, "    build_packages: {},", packages(&m.build_packages));
    o.push_str("    ffi_bridges: &[],\n");
    let _ = writeln!(o, "    build: {P}::BuildInfo {{");
    let _ = writeln!(o, "        backend: \"mvl-rust\",");
    let _ = writeln!(o, "        rustc_version: {},", opt(&b.rustc_version));
    let _ = writeln!(o, "        llvm_version: {},", opt(&b.llvm_version));
    let _ = writeln!(o, "        target: {},", s(&b.target));
    let _ = writeln!(o, "        profile: {},", s(&b.profile));
    let _ = writeln!(o, "        date: {},", s(&b.date));
    let _ = writeln!(o, "        host: {},", s(&b.host));
    let _ = writeln!(o, "        rustc_commit: {},", s(&b.rustc_commit));
    let _ = writeln!(o, "        rustc_channel: {},", s(&b.rustc_channel));
    let _ = writeln!(o, "        cargo_version: {},", s(&b.cargo_version));
    let _ = writeln!(o, "        cc_version: {},", s(&b.cc_version));
    let _ = writeln!(o, "        linker: {},", s(&b.linker));
    let _ = writeln!(o, "        opt_level: {},", s(&b.opt_level));
    // Cargo does not pass debug_assertions to build scripts; evaluate it in
    // the app crate, where manifest!() expands.
    o.push_str("        debug_assertions: cfg!(debug_assertions),\n");
    let _ = writeln!(o, "        panic: {},", s(&b.panic));
    let _ = writeln!(o, "        target_features: {},", list(&b.target_features));
    let _ = writeln!(o, "        overflow_checks: {},", b.overflow_checks);
    let _ = writeln!(
        o,
        "        profile_overrides: {},",
        list(&b.profile_overrides)
    );
    let _ = writeln!(o, "        features: {},", list(&b.features));
    let _ = writeln!(o, "        rustflags: {},", list(&b.rustflags));
    let _ = writeln!(o, "        rustc_wrapper: {},", list(&b.rustc_wrapper));
    let _ = writeln!(o, "        substitutions: {},", list(&b.substitutions));
    let _ = writeln!(o, "        vcs_commit: {},", s(&b.vcs_commit));
    let _ = writeln!(o, "        vcs_dirty: {},", b.vcs_dirty);
    let _ = writeln!(o, "        vcs_describe: {},", s(&b.vcs_describe));
    let _ = writeln!(o, "        lockfile_digest: {},", s(&b.lockfile_digest));
    let _ = writeln!(o, "        reproducible: {},", b.reproducible);
    let _ = writeln!(o, "        auditable: {},", b.auditable);
    o.push_str("    },\n");
    o.push_str("    licenses: &[],\n");
    let _ = writeln!(
        o,
        "    assurance: {P}::AssuranceInfo {{ extern_ratio: 0.0, extern_count: 0, total_functions: 0, requirements_proven: 0 }},"
    );
    let _ = writeln!(o, "    source_digest: {},", s(&m.source_digest));
    o.push_str("    native_deps: &[],\n");
    o.push_str("}\n");
    o
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn string_literals_are_escaped() {
        assert_eq!(s("a\"b\\c\n"), r#""a\"b\\c\n""#);
    }

    #[test]
    fn renders_package_with_git_source() {
        let p = OwnedPackage {
            name: "g".into(),
            version: "0.1.0".into(),
            purl: "pkg:cargo/g@0.1.0".into(),
            kind: "runtime",
            source: OwnedSource::Git {
                url: "https://x/g".into(),
                commit: "abc".into(),
            },
            checksum: String::new(),
        };
        let out = packages(&[p]);
        assert!(out.contains(
            "::mvl_manifest::PackageSource::Git { url: \"https://x/g\", commit: \"abc\" }"
        ));
        assert!(out.contains("kind: ::mvl_manifest::PackageKind::Runtime"));
    }
}
